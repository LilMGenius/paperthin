import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const skill = dirname(dirname(fileURLToPath(import.meta.url)));
const temps = [];

function repo(files) {
  const root = mkdtempSync(join(tmpdir(), 'scope-'));
  temps.push(root);
  spawnSync('git', ['init', '-q'], { cwd: root });
  for (const [path, body] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), body);
  }
  return root;
}

// Every call goes through a link to the skill folder, the way an installed skill is reached.
const linkRoot = mkdtempSync(join(tmpdir(), 'scope-link-'));
temps.push(linkRoot);
const link = join(linkRoot, 're0-style');
symlinkSync(skill, link, process.platform === 'win32' ? 'junction' : 'dir');

function cli(cwd, ...args) {
  const run = spawnSync(process.execPath, [join(link, 'scripts', 'scope.mjs'), ...args], { cwd, encoding: 'utf8' });
  return { status: run.status, stdout: run.stdout, stderr: run.stderr, json: () => JSON.parse(run.stdout) };
}

test.after(() => {
  for (const dir of temps) rmSync(dir, { recursive: true, force: true });
});

test('a file with a plain body and no attribute is clean and exits 0', () => {
  const root = repo({ 'a.js': 'export const a = 1;\n' });
  const run = cli(root, 'a.js', '--json');
  assert.equal(run.status, 0);
  const [f] = run.json().files;
  assert.equal(f.flagged, false);
  assert.deepEqual(f.markers, []);
  assert.equal(f.header, null);
});

test('linguist-generated and linguist-vendored attributes flag a file and exit 3', () => {
  const root = repo({
    '.gitattributes': 'gen.js linguist-generated\nvendor/** linguist-vendored\n',
    'gen.js': 'x\n',
    'vendor/v.js': 'x\n',
    'own.js': 'x\n',
  });
  const run = cli(root, 'gen.js', 'vendor/v.js', 'own.js', '--json');
  assert.equal(run.status, 3);
  const byFile = Object.fromEntries(run.json().files.map((f) => [f.file, f.attributes]));
  assert.deepEqual(byFile['gen.js'], ['linguist-generated']);
  assert.deepEqual(byFile['vendor/v.js'], ['linguist-vendored']);
  assert.deepEqual(byFile['own.js'], []);
});

test('an attribute explicitly unset does not flag the file', () => {
  const root = repo({ '.gitattributes': '* linguist-generated\nkeep.js -linguist-generated\n', 'keep.js': 'x\n' });
  const run = cli(root, 'keep.js', '--json');
  assert.equal(run.status, 0);
  assert.deepEqual(run.json().files[0].attributes, []);
});

test('a generated header within the first lines is found, one far below is not', () => {
  const root = repo({
    'top.js': '// Code generated by protoc. DO NOT EDIT.\nconst a = 1;\n',
    'deep.js': '\n'.repeat(30) + '// generated by hand, honest\n',
  });
  const run = cli(root, 'top.js', 'deep.js', '--json');
  const files = run.json().files;
  assert.equal(files[0].header.line, 1);
  assert.equal(files[1].header, null);
  assert.equal(files[1].flagged, false);
});

test('formatter and linter off markers are listed with their line numbers', () => {
  const body = ['const a = 1;', '// prettier-ignore', 'const  b =  2;', '/* eslint-disable no-console */', '# fmt: off', 'const c = 3; // ok'].join('\n') + '\n';
  const root = repo({ 'a.js': body });
  const run = cli(root, 'a.js', '--json');
  assert.equal(run.status, 3);
  assert.deepEqual(run.json().files[0].markers.map((m) => m.line), [2, 4, 5]);
});

test('config files from the file folder up to the repository root are listed', () => {
  const root = repo({ '.editorconfig': 'root = true\n', 'pkg/.prettierrc': '{}\n', 'pkg/src/a.js': 'x\n', 'other/.eslintrc.json': '{}\n' });
  const configs = cli(root, 'pkg/src/a.js', '--json').json().files[0].configs;
  assert.deepEqual([...configs].sort(), ['.editorconfig', 'pkg/.prettierrc']);
});

test('a missing path and a call with no path exit 2', () => {
  const root = repo({ 'a.js': 'x\n' });
  assert.equal(cli(root, 'nope.js').status, 2);
  assert.match(cli(root, 'nope.js').stderr, /no such path/);
  assert.equal(cli(root).status, 2);
  assert.equal(cli(root, '--bogus', 'a.js').status, 2);
});

test('the plain output names each finding and the totals', () => {
  const root = repo({ 'a.js': '// prettier-ignore\nx\n' });
  const run = cli(root, 'a.js');
  assert.equal(run.status, 3);
  assert.match(run.stdout, /a\.js {2}FLAGGED/);
  assert.match(run.stdout, /off marker: line 1/);
  assert.match(run.stdout, /1 flagged in 1 file\(s\)/);
});
